import argparse
import json
import pathlib
import yaml
from request_parser.main import request_parser_main

FIELDS = ["day", "hour", "sensor", "priority"]


def load_config(config_path: str) -> dict:
    with pathlib.Path(config_path).open("r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def clean_model_name(model: str) -> str:
    return model.replace(":", "_").replace(".", "_")


def parse_scenario(combined_path: pathlib.Path, model: str, cfg: dict) -> list:
    with combined_path.open("r", encoding="utf-8") as f:
        combined = json.load(f)

    results = []
    for task in combined["tasks"]:
        parsed = request_parser_main(task["generated_output"], model, cfg)
        ground_truth = task["ground_truth"]
        validation = task["validation"]
        results.append({
            "task_id": task["task_id"],
            "parsed": parsed,
            "parser_match": {
                f"{field}_match": parsed[field] == ground_truth[f"expected_{field}"]
                for field in FIELDS
            },
            "validation": {
                f"{field}_match": validation[f"{field}_match"]
                for field in FIELDS
            },
        })
    return results


def main():
    parser = argparse.ArgumentParser(
        description="Runs each configured parser model over the requests generated by KDF "
                    "and compares its labels with the ground truth. Resumable."
    )
    parser.add_argument("root_dir", type=str,
                        help="Root directory with {model}/{strategy}/temp_{T}/rep_{r}/scenario_{idx}/.")
    parser.add_argument("--models", type=str, default=None,
                        help="Comma-separated parser models (e.g. 'llama3.1:8b,phi4:14b'). "
                             "Default: the models in config.yaml.")
    args = parser.parse_args()

    cfg = load_config("config.yaml")
    models = ([m.strip() for m in args.models.split(",") if m.strip()]
              if args.models else cfg["models"])
    combined_paths = sorted(pathlib.Path(args.root_dir).glob(
        "*/*/temp_*/rep_*/scenario_*/ollama_prompts_combined.json"
    ))
    total_run = total_skipped = 0

    for combined_path in combined_paths:
        scenario_dir = combined_path.parent
        for model in models:
            output_path = scenario_dir / f"parsed_requests_{clean_model_name(model)}.json"
            if output_path.exists():
                total_skipped += 1
                print(f"  [SKIP] {output_path}: already exists, skipping.")
                continue

            total_run += 1
            print(f"  [RUN] {scenario_dir} | parser={model}...")
            results = parse_scenario(combined_path, model, cfg)
            output_path.write_text(
                json.dumps(results, indent=2, ensure_ascii=False),
                encoding="utf-8"
            )
            print(f"  [OK]  {output_path}")

    print("\n" + "=" * 70)
    print(" SUMMARY")
    print("=" * 70)
    print(f"  Scenario files found  : {len(combined_paths)}")
    print(f"  Parsed in this run    : {total_run}")
    print(f"  Skipped (existing)    : {total_skipped}")


if __name__ == "__main__":
    main()
